# AI練習01：輸出字串
# 試著利用print函數在螢幕上輸出文字"Hello World"
# 說明：print為Python的內建函數，可用於將文字或變數輸出到螢幕上
#       print()原先只有一個引號"可用，但在Python 3.6後，單引號'也可用於輸出字串
#       print（）輸出時，用逗號分開，引號前後會有空格，若用加號連結，則引號前後不會有空格
#       Python 3.6後，也可以在print()中使用f-string，語法為f"字串{變數}"
# 補充：Python 的單行註解是用#號，多行註解是用連續三個雙引號"""或單引號''' 來包含區塊

print("Hello World")

# 用逗號分開，引號前後會有空格
print("Hello","World")

# 用加號連結，引號前後不會有空格
print("Hello"+"World")


