# 常見運算子
a = 2
b = 3 
# 算數
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b) # 取餘數
print(a // b) # 取商
print(a ** b) # 次方

# 比較 (布林)
print(a == b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)
print(a != b)

# 邏輯 (布林): 條件1 and/or/not 條件2 and/or/not 條件3....
print(True and False)
print(True and True)
print(False or False)
print(True or False)
print(not True)

# assign: =
a = 5
a += 2 # a = a+2
a -= 2
a *= 2
a /= 2
a %= 2
a //= 2
a **= 2

# in: 成員運算子
# is: 身分運算子
a = [1,2,3]
b = a
c = a.copy()
print(a is b) # True
print(a is c) # False

